-- GB-001 / GB-003: the dispatcher, ADDON_LOADED bootstrap and group-only handlers.

return function(T, H)
    T.case("GBIS_INITIALIZED fires once, only for our own ADDON_LOADED", function()
        H.Install()
        local ns = H.Load()
        local count = 0
        ns.Events:Register("GBIS_INITIALIZED", function() count = count + 1 end, "test")
        H.Fire("ADDON_LOADED", "SomeOtherAddon")
        T.eq(count, 0, "other addon")
        H.Fire("ADDON_LOADED", "GudaBiS")
        T.eq(count, 1, "ours")
        T.ok(ns.db ~= nil, "database ready before GBIS_INITIALIZED")
        H.Fire("ADDON_LOADED", "GudaBiS")
        T.eq(count, 1, "not twice")
        T.noErrors()
    end)

    T.case("WoW events register the frame; custom events never do", function()
        local ns = H.Boot()
        ns.Events:Register("UNIT_AURA", function() end, "a")
        ns.Events:Register("GBIS_SOMETHING", function() end, "a")
        T.ok(H.Registered("UNIT_AURA"), "wow event")
        T.ok(not H.Registered("GBIS_SOMETHING"), "custom event")
        ns.Events:Unregister("UNIT_AURA", "a")
        T.ok(not H.Registered("UNIT_AURA"), "unregistered when the last owner leaves")
    end)

    T.case("owners are independent", function()
        local ns = H.Boot()
        local a, b = 0, 0
        ns.Events:Register("GBIS_X", function() a = a + 1 end, "a")
        ns.Events:Register("GBIS_X", function() b = b + 1 end, "b")
        ns.Events:Unregister("GBIS_X", "a")
        ns.Events:Fire("GBIS_X")
        T.eq(a, 0, "a removed")
        T.eq(b, 1, "b still called")
    end)

    T.case("handler arguments arrive after the event name", function()
        local ns = H.Boot()
        local got
        ns.Events:Register("GBIS_ARGS", function(event, x, y) got = event .. x .. y end, "a")
        ns.Events:Fire("GBIS_ARGS", 1, 2)
        T.eq(got, "GBIS_ARGS12", "args")
    end)

    T.case("a failing handler reaches the error handler once and spares the others", function()
        local ns = H.Boot()
        local other = 0
        ns.Events:Register("GBIS_BOOM", function() error("boom") end, "bad")
        ns.Events:Register("GBIS_BOOM", function() other = other + 1 end, "good")
        ns.Events:Fire("GBIS_BOOM")
        ns.Events:Fire("GBIS_BOOM")
        T.eq(#H.errors, 1, "error shown once")
        T.eq(other, 2, "other handler ran both times")
    end)

    T.case("group handlers are registered only while in a group", function()
        local ns = H.Boot()
        local hits, joined, left = 0, 0, 0
        ns.Events:Register("GBIS_GROUP_JOINED", function() joined = joined + 1 end, "t")
        ns.Events:Register("GBIS_GROUP_LEFT", function() left = left + 1 end, "t")
        ns.Events:RegisterGroup("START_LOOT_ROLL", function() hits = hits + 1 end, "Loot")
        T.ok(not H.Registered("START_LOOT_ROLL"), "solo: not registered")
        H.SetGroup(true)
        T.ok(H.Registered("START_LOOT_ROLL"), "group: registered")
        T.ok(ns.Events:IsInGroup(), "IsInGroup")
        T.eq(joined, 1, "joined fired")
        H.Fire("START_LOOT_ROLL", 7)
        T.eq(hits, 1, "handler called")
        H.SetGroup(true)
        T.eq(joined, 1, "no second join on a roster change")
        H.SetGroup(false)
        T.ok(not H.Registered("START_LOOT_ROLL"), "left: unregistered")
        T.eq(left, 1, "left fired")
        T.noErrors()
    end)

    T.case("registering while already in a group takes effect at once", function()
        local ns = H.Boot()
        ns.Events:RegisterGroup("CHAT_MSG_RAID", function() end, "A")
        H.SetGroup(true)
        ns.Events:RegisterGroup("CHAT_MSG_RAID_WARNING", function() end, "B")
        T.ok(H.Registered("CHAT_MSG_RAID_WARNING"), "registered immediately")
    end)

    T.case("UnregisterGroup removes it for good", function()
        local ns = H.Boot()
        ns.Events:RegisterGroup("CHAT_MSG_RAID", function() end, "Chat")
        H.SetGroup(true)
        ns.Events:UnregisterGroup("CHAT_MSG_RAID", "Chat")
        T.ok(not H.Registered("CHAT_MSG_RAID"), "removed")
        H.SetGroup(false)
        H.SetGroup(true)
        T.ok(not H.Registered("CHAT_MSG_RAID"), "not back after rejoin")
    end)

    T.case("already in a group at login", function()
        H.Install()
        H.inGroup = true
        local ns = H.Load()
        H.Fire("ADDON_LOADED", "GudaBiS")
        ns.Events:RegisterGroup("START_LOOT_ROLL", function() end, "Loot")
        T.ok(H.Registered("START_LOOT_ROLL"), "registered from the first call")
    end)
end
