-- GB-003: debug log ring buffer, reload persistence and /gbis log.

return function(T, H)
    T.case("ns:Debug writes to the log, reaches chat only in debug mode", function()
        local ns = H.Boot()
        ns:Debug("quiet", 1)
        T.ok(ns.Log:Lines()[1]:find("%[debug%] quiet 1$"), "logged")
        T.ok(not H.Printed("quiet", true), "not in chat")
        H.Slash("debug on")
        ns:Debug("loud", nil)
        T.ok(H.Printed("loud nil", true), "in chat")
    end)

    T.case("ring buffer keeps the last 300 lines, oldest first", function()
        local ns = H.Boot()
        for i = 1, 305 do ns.Log:Add("t", i) end
        local lines = ns.Log:Lines()
        T.eq(#lines, 300, "count")
        T.ok(lines[1]:find("%] 6$"), "oldest kept")
        T.ok(lines[300]:find("%] 305$"), "newest")
    end)

    T.case("lines survive a reload, before this session's", function()
        local ns = H.Boot()
        ns.Log:Add("t", "before")
        H.Fire("PLAYER_LOGOUT")
        local saved = _G.GudaBiS_DB
        T.eq(#saved.log, 1, "saved")
        ns = H.Boot({ saved = saved })
        local lines = ns.Log:Lines()
        T.ok(lines[1]:find("before$"), "old line first")
        T.ok(lines[2]:find("reload$"), "reload marker")
    end)

    T.case("/gbis log toggles the window, /gbis log clear empties it", function()
        local ns = H.Boot()
        ns.Log:Add("t", "x")
        H.Slash("log")
        T.ok(ns.Log.frame and ns.Log.frame:IsShown(), "shown")
        T.ok(ns.Log.frame.edit.shownText:find("x$"), "text")
        H.Slash("log")
        T.ok(not ns.Log.frame:IsShown(), "hidden")
        H.Slash("log clear")
        T.eq(#ns.Log:Lines(), 0, "cleared")
        T.ok(H.Printed("Debug log cleared.", true), "message")
        T.noErrors()
    end)

    T.case("new lines while the window is open redraw once, later", function()
        local ns = H.Boot()
        H.Slash("log")
        ns.Log:Add("t", "a")
        ns.Log:Add("t", "b")
        T.eq(#H.timers, 1, "one pending redraw")
        H.Advance(0.2)
        T.ok(ns.Log.frame.edit.shownText:find("b$"), "redrawn")
    end)
end
