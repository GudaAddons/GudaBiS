"""Build Data/<Flavor>/Lists.lua from Wowhead BiS guides saved as HTML.

Usage (WSL):
  python3 tools/pipeline/build.py --source /mnt/g/addon-data/GudaBis --flavor TBC --default-phase 4

Every *.htm / *.html in --source is read. The output is deterministic (sorted), so
regenerating unchanged pages gives no diff. Never edit the output by hand
(RULES.md Rule 7): fix the parser, or add an override in tools/overrides/.
"""

import argparse
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))

import wowhead  # noqa: E402

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", ".."))


def lists_from_guide(guide):
    result = []
    spec = guide["spec"]
    for index, gear_set in enumerate(guide["sets"], start=1):
        items, enchants, gems, alts = {}, {}, {}, {}
        for slot, entry in gear_set["slots"].items():
            items[slot] = entry["item"]
            if entry["enchant"]:
                enchants[slot] = entry["enchant"]
            if entry["gems"]:
                gems[slot] = entry["gems"]
        for slot, rows in guide["rows"].items():
            chosen = {items.get(s) for s in _paired(slot)}
            rest = [item for item in rows if item not in chosen]
            if rest:
                alts[slot] = rest
        missing = sorted(i for i in items.values() if i not in guide["page_items"])
        if missing:
            print(f"  note: {spec['key']} phase {guide['phase']} '{gear_set['name']}': "
                  f"set items not in the page tables: {missing}", file=sys.stderr)
        result.append({
            "id": f"{spec['key']}:{guide['phase']}:{index}",
            "spec": spec["key"], "class": spec["class"], "specID": spec["specID"], "tree": spec["tree"],
            "phase": guide["phase"], "set": gear_set["name"], "faction": gear_set["faction"],
            "url": guide["url"], "updated": guide["updated"],
            "items": items, "enchants": enchants, "gems": gems, "alts": alts,
        })
    return result


def _paired(slot):
    if slot in (11, 12):
        return (11, 12)
    if slot in (13, 14):
        return (13, 14)
    return (slot,)


def lua_value(value, indent):
    pad = "    " * indent
    if value is None:
        return "nil"
    if isinstance(value, bool):
        return "true" if value else "false"
    if isinstance(value, int):
        return str(value)
    if isinstance(value, str):
        return '"' + value.replace("\\", "\\\\").replace('"', '\\"') + '"'
    if isinstance(value, list):
        return "{ " + ", ".join(lua_value(v, indent) for v in value) + " }"
    if isinstance(value, dict):
        lines = ["{"]
        for key in sorted(value, key=lambda k: (isinstance(k, str), k)):
            v = value[key]
            if v is None:
                continue
            name = f"[{key}]" if isinstance(key, int) else key
            lines.append(f"{pad}    {name} = {lua_value(v, indent + 1)},")
        lines.append(pad + "}")
        return "\n".join(lines)
    raise TypeError(type(value))


FIELD_ORDER = ["id", "spec", "class", "specID", "tree", "phase", "set", "faction", "url", "updated",
               "items", "enchants", "gems", "alts"]


def render(flavor, default_phase, lists):
    out = [
        f"-- Generated by tools/pipeline/build.py from Wowhead BiS guides ({flavor}). Do not edit by hand:",
        "-- fix the pipeline or tools/overrides/ and regenerate (RULES.md Rule 7).",
        "-- Slots are INVSLOT numbers; enchants are spell IDs; gems are item IDs in socket order;",
        "-- alts are the guide's other items for that slot, in page order.",
        "",
        "local addonName, ns = ...",
        "",
        "ns.Data:Register({",
        f'    flavor = "{flavor}",',
        f"    defaultPhase = {default_phase},",
        '    source = "Wowhead",',
        "    lists = {",
    ]
    for entry in sorted(lists, key=lambda e: e["id"]):
        out.append("        {")
        for field in FIELD_ORDER:
            value = entry[field]
            if value is None or value == {}:
                continue
            out.append(f"            {field} = {lua_value(value, 3)},")
        out.append("        },")
    out += ["    },", "})", ""]
    return "\n".join(out)


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--source", required=True)
    parser.add_argument("--flavor", required=True)
    parser.add_argument("--default-phase", type=int, required=True)
    args = parser.parse_args()

    files = sorted(f for f in os.listdir(args.source) if f.lower().endswith((".htm", ".html")))
    if not files:
        sys.exit(f"no saved pages in {args.source}")
    lists, seen = [], {}
    for name in files:
        with open(os.path.join(args.source, name), encoding="utf-8", errors="replace") as handle:
            guide = wowhead.parse(handle.read())
        key = (guide["spec"]["key"], guide["phase"])
        if key in seen:
            sys.exit(f"{name}: same spec and phase as {seen[key]}")
        seen[key] = name
        made = lists_from_guide(guide)
        print(f"{name}: {key[0]} phase {key[1]}, {len(made)} set(s)")
        lists.extend(made)

    out_dir = os.path.join(ROOT, "Data", args.flavor)
    os.makedirs(out_dir, exist_ok=True)
    out_path = os.path.join(out_dir, "Lists.lua")
    with open(out_path, "w", encoding="utf-8", newline="\n") as handle:
        handle.write(render(args.flavor, args.default_phase, lists))
    print(f"wrote {out_path}: {len(lists)} list(s)")


if __name__ == "__main__":
    main()
