"""Build Data/<Flavor>/Lists.lua from Wowhead BiS guides saved as HTML.

Usage (WSL):
  python3 tools/pipeline/build.py --source /mnt/g/addon-data/GudaBis/TBC --flavor TBC --default-phase 4

Pages are found under <source>/<Class>/<Spec>/ (Rogue: <source>/Rogue/); the "_files"
folders a browser's "Save complete" writes are skipped. Pages of the same spec and
phase are merged (their sets numbered on), a page whose title was already read for that
spec is skipped as a duplicate, and a page that cannot be read is reported and skipped,
so one bad page never stops the build. The report goes to stderr.

The output is deterministic (sorted), so regenerating unchanged pages gives no diff.
Never edit the output by hand (RULES.md Rule 7): fix the parser and regenerate.
"""

import argparse
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))

import gearplanner  # noqa: E402
import specs  # noqa: E402
import wowhead  # noqa: E402

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", ".."))


def _phase_key(phase):
    return "res" if phase == "res" else str(phase)


def lists_from_guide(guide, first_index=1):
    result = []
    spec = guide["spec"]
    any_phase = guide["phase"] == "res"
    for index, gear_set in enumerate(guide["sets"], start=first_index):
        items, enchants, gems, alts = {}, {}, {}, {}
        for slot, entry in gear_set["slots"].items():
            items[slot] = entry["item"]
            if entry["enchant"]:
                enchants[slot] = entry["enchant"]
            if entry["gems"]:
                gems[slot] = entry["gems"]
        for slot, rows in guide["rows"].items():
            chosen = {items.get(s) for s in _paired(slot)}
            rest = [item for item in rows if item not in chosen]
            if rest:
                alts[slot] = rest
        result.append({
            "id": f"{spec['key']}:{_phase_key(guide['phase'])}:{index}",
            "spec": spec["key"], "class": spec["class"], "specID": spec["specID"], "tree": spec["tree"],
            "phase": None if any_phase else guide["phase"], "anyPhase": True if any_phase else None,
            "set": gear_set["name"], "faction": gear_set["faction"],
            "url": guide["url"], "updated": guide["updated"],
            "items": items, "enchants": enchants, "gems": gems, "alts": alts,
        })
    return result


def _paired(slot):
    if slot in (11, 12):
        return (11, 12)
    if slot in (13, 14):
        return (13, 14)
    return (slot,)


def lua_value(value, indent):
    pad = "    " * indent
    if value is None:
        return "nil"
    if isinstance(value, bool):
        return "true" if value else "false"
    if isinstance(value, int):
        return str(value)
    if isinstance(value, str):
        return '"' + value.replace("\\", "\\\\").replace('"', '\\"') + '"'
    if isinstance(value, list):
        return "{ " + ", ".join(lua_value(v, indent) for v in value) + " }"
    if isinstance(value, dict):
        lines = ["{"]
        for key in sorted(value, key=lambda k: (isinstance(k, str), k)):
            v = value[key]
            if v is None:
                continue
            name = f"[{key}]" if isinstance(key, int) else key
            lines.append(f"{pad}    {name} = {lua_value(v, indent + 1)},")
        lines.append(pad + "}")
        return "\n".join(lines)
    raise TypeError(type(value))


FIELD_ORDER = ["id", "spec", "class", "specID", "tree", "phase", "anyPhase", "set", "faction", "url",
               "updated", "items", "enchants", "gems", "alts"]


def render(flavor, default_phase, lists):
    out = [
        f"-- Generated by tools/pipeline/build.py from Wowhead BiS guides ({flavor}). Do not edit by hand:",
        "-- fix the pipeline or tools/overrides/ and regenerate (RULES.md Rule 7).",
        "-- Slots are INVSLOT numbers; enchants are spell IDs; gems are item IDs in socket order;",
        "-- alts are the guide's other items for that slot, in page order; anyPhase lists",
        "-- (resistance gear) belong to every phase.",
        "",
        "local addonName, ns = ...",
        "",
        "ns.Data:Register({",
        f'    flavor = "{flavor}",',
        f"    defaultPhase = {default_phase},",
        '    source = "Wowhead",',
        "    lists = {",
    ]
    for entry in sorted(lists, key=lambda e: e["id"]):
        out.append("        {")
        for field in FIELD_ORDER:
            value = entry[field]
            if value is None or value == {}:
                continue
            out.append(f"            {field} = {lua_value(value, 3)},")
        out.append("        },")
    out += ["    },", "})", ""]
    return "\n".join(out)


def saved_pages(source):
    """(path, class folder, spec folder, file name) for every saved guide page, sorted,
    skipping the browser's "_files" folders."""
    found = []
    for dirpath, dirnames, filenames in os.walk(source):
        dirnames[:] = sorted(d for d in dirnames if not d.endswith("_files"))
        for name in filenames:
            if not name.lower().endswith((".htm", ".html")):
                continue
            parts = os.path.relpath(os.path.join(dirpath, name), source).split(os.sep)
            if len(parts) == 3:
                found.append((os.path.join(dirpath, name), parts[0], parts[1], name))
            elif len(parts) == 2:
                found.append((os.path.join(dirpath, name), parts[0], "", name))
    return sorted(found)


def collect(source):
    """All lists, plus the report lines."""
    lists, report = [], []
    titles = {}
    next_index = {}
    for path, class_folder, spec_folder, name in saved_pages(source):
        where = os.path.relpath(path, source)
        try:
            spec = specs.lookup(class_folder, spec_folder)
            with open(path, encoding="utf-8", errors="replace") as handle:
                guide = wowhead.parse(handle.read(), spec, name)
        except (specs.UnknownSpec, wowhead.GuideError, gearplanner.GearPlannerError) as err:
            report.append(f"SKIPPED {where}: {err}")
            continue
        seen = titles.get((spec["key"], guide["title"]))
        if seen:
            report.append(f"SKIPPED {where}: same page as {seen}")
            continue
        titles[(spec["key"], guide["title"])] = where
        group = (spec["key"], _phase_key(guide["phase"]))
        made = lists_from_guide(guide, next_index.get(group, 1))
        next_index[group] = next_index.get(group, 1) + len(made)
        lists.extend(made)
        sets = ", ".join(s["name"] for s in guide["sets"])
        report.append(f"ok      {where}: {spec['key']} phase {_phase_key(guide['phase'])}: {sets}")
        for warning in guide["warnings"]:
            report.append(f"        {where}: {warning}")
    _number_repeated_names(lists)
    return lists, report


def _number_repeated_names(lists):
    """Sets of one spec and phase that end up with the same name once the parentheses are
    dropped get "#2", "#3"... so the dropdown can tell them apart."""
    seen = {}
    for entry in lists:
        group = (entry["spec"], entry["phase"], entry["anyPhase"], entry["faction"], entry["set"])
        seen[group] = seen.get(group, 0) + 1
        if seen[group] > 1:
            entry["set"] = f"{entry['set']} #{seen[group]}"


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--source", required=True)
    parser.add_argument("--flavor", required=True)
    parser.add_argument("--default-phase", type=int, required=True)
    args = parser.parse_args()

    lists, report = collect(args.source)
    for line in report:
        print(line, file=sys.stderr)
    if not lists:
        sys.exit(f"no usable pages in {args.source}")

    out_dir = os.path.join(ROOT, "Data", args.flavor)
    os.makedirs(out_dir, exist_ok=True)
    out_path = os.path.join(out_dir, "Lists.lua")
    with open(out_path, "w", encoding="utf-8", newline="\n") as handle:
        handle.write(render(args.flavor, args.default_phase, lists))
    print(f"wrote {out_path}: {len(lists)} list(s)")


if __name__ == "__main__":
    main()
